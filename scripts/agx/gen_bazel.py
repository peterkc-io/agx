#!/usr/bin/env python3
"""Generate first-party Bazel rules from Cargo metadata and overrides."""

import argparse
import fnmatch
import json
from pathlib import Path
import posixpath
import re
import subprocess
import sys
from typing import Mapping, Sequence


ROOT = Path(__file__).resolve().parents[2]
HEADER = "# Generated by scripts/agx/gen_bazel.py; do not edit.\n"
LIST_ATTRS = ("data", "compile_data")
DICT_ATTRS = ("env", "rustc_env")


def rule_name(kind: str, name: str) -> str:
    """Keep Cargo unit kinds visible and avoid lib/bin name collisions."""
    if kind in ("lib", "bin"):
        return name
    return kind + "__" + name


def file_label(path: str, package_dirs: Sequence[str]) -> str:
    for directory in sorted(package_dirs, key=len, reverse=True):
        if path.startswith(directory + "/"):
            return "//" + directory + ":" + path[len(directory) + 1:]
    return "//:" + path


def render_rule(kind: str, attrs: Mapping[str, str]) -> str:
    lines = [kind + "("]
    lines.extend("    " + key + " = " + value + ","
                 for key, value in attrs.items())
    return "\n".join(lines + [")", ""])


def starlark(value) -> str:
    # JSON strings/lists/dicts are also Starlark, but booleans are not.
    if isinstance(value, bool):
        return "True" if value else "False"
    return json.dumps(value, sort_keys=True)


def generate(metadata: Mapping, overrides: Mapping,
             source_files: Sequence[str]) -> dict:
    """Return relative BUILD paths and contents without reading or writing."""
    root = Path(metadata["workspace_root"])
    members = set(metadata["workspace_members"])
    packages = [p for p in metadata["packages"] if p["id"] in members]
    directories = {
        p["name"]: Path(p["manifest_path"]).parent.relative_to(root).as_posix()
        for p in packages
    }
    libs = {
        p["name"]: t["name"]
        for p in packages for t in p["targets"] if "lib" in t["kind"]
    }
    target_overrides = overrides.get("targets", {})
    used_overrides = set()
    generated = {}
    for package in sorted(packages, key=lambda p: p["name"]):
        directory = directories[package["name"]]
        content = [HEADER, 'load("@crates//:defs.bzl", "aliases", '
                   '"all_crate_deps")\n',
                   'load("@rules_rust//rust:defs.bzl", "rust_binary", '
                   '"rust_doc_test", "rust_library", "rust_test")\n',
                   'package(default_visibility = ["//visibility:public"])\n',
                   'exports_files(glob(["**"], '
                   'exclude = ["BUILD.bazel"]))\n']
        for target in package["targets"]:
            name = target["name"]
            if target.get("required-features"):
                raise ValueError(
                    f"{package['name']}:{name}: required-features unsupported"
                )
            kind = target["kind"][0]
            if kind not in ("lib", "bin", "test", "example"):
                raise ValueError(
                    f"{package['name']}:{name}: unsupported {kind}"
                )
            target_path = posixpath.normpath(
                Path(target["src_path"]).relative_to(root).as_posix()
            )
            source_dir = target_path.rsplit("/", 1)[0]
            if kind == "lib":
                source_dir = directory + "/src"
            sources = [f for f in source_files if f.endswith(".rs")
                       and f.startswith(source_dir + "/")]
            sources = sorted(set(sources + [target_path]))
            labels = [file_label(f, list(directories.values()))
                      for f in sources]
            modes = [(kind, "rust_library" if kind == "lib"
                      else "rust_test" if kind == "test"
                      else "rust_binary")]
            if kind != "test" and target.get("test", False):
                modes.append((kind + "_test", "rust_test"))
            if kind == "lib" and target.get("doctest", False):
                modes.append(("doc", "rust_doc_test"))
            for mode, rule in modes:
                bazel_name = rule_name(mode, name)
                label = f"//{directory}:{bazel_name}"
                override = target_overrides.get(label, {})
                if label in target_overrides:
                    used_overrides.add(label)
                is_test = rule in ("rust_test", "rust_doc_test")
                dev = is_test or kind == "example"
                attrs = {"name": starlark(bazel_name)}
                unit = mode in ("lib_test", "bin_test", "example_test")
                if unit or mode == "doc":
                    attrs["crate"] = starlark(":" + rule_name(kind, name))
                else:
                    attrs.update({
                        "crate_name": starlark(name.replace("-", "_")),
                        "crate_root": starlark(file_label(
                            target_path, list(directories.values()))),
                        "srcs": starlark(labels),
                        "edition": starlark(target["edition"]),
                        "version": starlark(package["version"]),
                    })
                if mode != "doc":
                    local_deps = []
                    local_aliases = {}
                    for dep in package["dependencies"]:
                        if dep["name"] not in libs:
                            continue
                        if dep["kind"] not in (None, "dev" if dev else None):
                            continue
                        if dep.get("target"):
                            raise ValueError(
                                f"{label}: conditional workspace dependency"
                            )
                        dep_label = ("//" + directories[dep["name"]] + ":"
                                     + libs[dep["name"]])
                        local_deps.append(dep_label)
                        if dep.get("rename"):
                            local_aliases[dep_label] = dep["rename"]
                    if kind != "lib" and not unit:
                        lib = libs.get(package["name"])
                        if lib:
                            local_deps.append(":" + lib)
                    flags = "normal = True"
                    macro_flags = "proc_macro = True"
                    if dev:
                        flags += ", normal_dev = True"
                        macro_flags += ", proc_macro_dev = True"
                    attrs["deps"] = (starlark(sorted(set(local_deps)))
                                     + " + all_crate_deps(" + flags + ")")
                    attrs["proc_macro_deps"] = (
                        "all_crate_deps(" + macro_flags + ")"
                    )
                    attrs["aliases"] = (
                        starlark(local_aliases)
                        + " | aliases(" + flags + ", " + macro_flags + ")"
                    )
                    env = {"CARGO_MANIFEST_DIR": directory}
                    env.update(override.get("rustc_env", {}))
                    attrs["rustc_env"] = starlark(env)
                for attr in LIST_ATTRS + DICT_ATTRS:
                    if attr in override:
                        if attr == "env" and not is_test:
                            raise ValueError(f"{label}: env requires a test")
                        if attr != "rustc_env":
                            attrs[attr] = starlark(override[attr])
                if is_test:
                    tags = ["block-network"]
                    if override.get("kernel"):
                        tags.append("agx-kernel")
                        data = list(override.get("data", []))
                        data.append("//:bazel_kernel_python")
                        attrs["data"] = starlark(data)
                        env = dict(override.get("env", {}))
                        env.update({
                            "AGX_BAZEL_KERNEL": "1",
                            "AGX_BAZEL_KERNEL_PREFIX":
                                "$(rootpath //:bazel_kernel_python)",
                        })
                        attrs["env"] = starlark(env)
                        attrs["args"] = starlark(["--nocapture"])
                    attrs["tags"] = starlark(tags)
                content.append(render_rule(rule, attrs))
        generated[directory + "/BUILD.bazel"] = "\n".join(content)
    unused = sorted(set(target_overrides) - used_overrides)
    if unused:
        raise ValueError("Overrides name absent targets: " + ", ".join(unused))
    root_content = [HEADER,
                    'load("//:scripts/agx/bazel/defs.bzl", '
                    '"agx_kernel_python", "agx_test_wrapper")\n',
                    'package(default_visibility = ["//visibility:public"])',
                    'exports_files(["Cargo.toml", "Cargo.lock", '
                    '"scripts/agx/Cargo.Bazel.lock"])\n']
    for name, group in sorted(overrides.get("filegroups", {}).items()):
        paths = [p for p in source_files
                 if any(fnmatch.fnmatchcase(p, pattern)
                        for pattern in group["patterns"])]
        root_content.append(render_rule("filegroup", {
            "name": starlark(name),
            "srcs": starlark([file_label(p, list(directories.values()))
                              for p in sorted(paths)]),
        }))
    root_content.extend([
        render_rule("filegroup", {
            "name": starlark("bazel_binaries"),
            "srcs": starlark(sorted(
                "//" + directories[p["name"]] + ":" + t["name"]
                for p in packages for t in p["targets"]
                if t["kind"] == ["bin"]
            )),
        }),
        render_rule("agx_test_wrapper", {
            "name": starlark("bazel_test_env"),
            "launcher": starlark("scripts/agx/bazel/test_env.sh"),
            "script": starlark("scripts/agx/bazel/test_env.py"),
        }),
        render_rule("agx_kernel_python", {
            "name": starlark("bazel_kernel_python"),
            "srcs": starlark([":runtime_sources"]),
            "manifest": starlark("prime-agent-runtime/pyproject.toml"),
            "builder": starlark("scripts/agx/bazel/build_kernel.py"),
            "agx": starlark("//crates/pa-cli:agx"),
            "uv": ('select({"@platforms//os:macos": '
                   '"@agx_uv_macos//:uv", "//conditions:default": '
                   '"@agx_uv_linux//:uv"})'),
        }),
    ])
    generated["BUILD.bazel"] = "\n".join(root_content)
    return generated


def cargo_patch_dirs(manifest: str) -> list:
    """Read inline path entries in Cargo's patch tables (Python 3.9).

    Reject unsupported patch syntax instead of silently excluding the
    wrong directory. No TOML dependency is needed for this workspace.
    """
    directories = []
    in_patch = False
    for line in manifest.splitlines():
        line = line.strip()
        if line.startswith("["):
            in_patch = line.startswith("[patch.")
        elif in_patch and line and not line.startswith("#"):
            entry = re.fullmatch(r"[^=]+\s*=\s*\{(.*)}\s*(?:#.*)?", line)
            if entry is None:
                raise ValueError("Unsupported Cargo patch entry: " + line)
            path_field = re.search(
                r"(?:^|,)\s*path\s*=\s*(\"(?:[^\"\\]|\\.)*\"|'[^']*')",
                entry.group(1),
            )
            if path_field is None:
                continue
            quoted = path_field.group(1)
            path = (quoted[1:-1] if quoted.startswith("'")
                    else json.loads(quoted))
            if (not path or Path(path).is_absolute()
                    or ".." in Path(path).parts):
                raise ValueError("Cargo patch path must stay in workspace: "
                                 + path)
            directories.append(posixpath.normpath(path))
    return directories


def first_party_builds(paths: Sequence[str],
                       patch_dirs: Sequence[str]) -> set:
    # Native path-patch output: rules_rust 0.74.0 rendering.rs:496-500.
    return {path for path in paths if Path(path).name == "BUILD.bazel"
            and not any(path.startswith(directory + "/")
                        for directory in patch_dirs)}


def differences(expected: Mapping[str, str],
                actual: Mapping[str, str]) -> list:
    problems = []
    for name in sorted(set(expected) | set(actual)):
        if name not in actual:
            problems.append("Missing: " + name)
        elif name not in expected:
            problems.append("Extra: " + name)
        elif expected[name] != actual[name]:
            problems.append("Stale: " + name)
    return problems


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    try:
        metadata_run = subprocess.run(
            ["cargo", "metadata", "--locked", "--no-deps",
             "--format-version", "1"],
            cwd=ROOT, check=True, capture_output=True, text=True,
        )
        metadata = json.loads(metadata_run.stdout)
        overrides = json.loads(
            (ROOT / "scripts/agx/bazel_overrides.json").read_text()
        )
        inventory = subprocess.run(
            ["git", "ls-files", "--cached", "--others",
             "--exclude-standard", "-z"],
            cwd=ROOT, check=True, capture_output=True,
        )
        paths = sorted({p.decode() for p in inventory.stdout.split(b"\0")
                        if p and (ROOT / p.decode()).is_file()})
        expected = generate(metadata, overrides, paths)
        # Git-aware discovery avoids ignored target/ and Bazel output trees.
        patch_dirs = cargo_patch_dirs((ROOT / "Cargo.toml").read_text())
        builds = first_party_builds(paths, patch_dirs)
        actual = {p: (ROOT / p).read_text() for p in builds}
        problems = differences(expected, actual)
        if args.check:
            for problem in problems:
                print(problem, file=sys.stderr)
            if problems:
                return 1
        else:
            extra = sorted(builds - set(expected))
            if extra:
                for name in extra:
                    print("Extra: " + name, file=sys.stderr)
                return 1
            for name, text in expected.items():
                (ROOT / name).write_text(text)
        print(f"Bazel BUILD files match {len(expected)} generated files.")
        return 0
    except (OSError, ValueError, subprocess.CalledProcessError) as error:
        print(f"Bazel generation failed: {error}", file=sys.stderr)
        if isinstance(error, subprocess.CalledProcessError):
            print(error.stderr, file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
